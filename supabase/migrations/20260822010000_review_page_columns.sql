-- ── 포스터 경로 — **크롤러가 쓰고 min_job이 읽는다** ────────────────────────
--
-- 구조화 단계에서 그림·PDF 바이트를 Storage(`postings` 버킷 · 비공개)에 올리고 그 경로를
-- 여기 적는다. 경로 규약: `{source_key}/{source_data_id}/{n}.{ext}`
--
-- ⚠️ **순서가 원문 순서다**(0부터). 포스터가 여러 장인 공고는 그 순서로 봐야 말이 된다.
--
-- ⚠️ **왜 `source_data`가 아니라 여기인가** — 그 테이블은 write-once 원문 증거이고 갱신 허용
--    칸이 셋뿐이다(`structured_at`·`structure_attempts`·`last_structure_error`). 넷째를 더하면
--    그 보호가 느슨해진다. 반면 `review_data`는 구조화가 만드는 행이라 여기가 제 자리다.
--
-- ⚠️ **비어 있음이 신호다** — `source_data.image_urls`는 차 있는데 이게 비었으면 **그림을 못
--    받았다**는 뜻이다(바이트를 못 받으면 올릴 것도 없다). 그래서 등급 근거를 담는 별도 칸을
--    두지 않는다(REVIEW_PAGE §4.4).
alter table review_data
  add column if not exists poster_paths text[] not null default '{}';

-- ── 검수 메모 — **min_job admin이 쓰고 크롤러는 읽어서 되쓸 뿐이다** ──────────
--
-- ⚠️ **거절 사유를 목록(enum)으로 만들지 않았다**(운영자 결정 2026-08-22). 어떤 이유가 실제로
--    반복되는지 **실측이 0건**이라, 목록을 먼저 만들면 검수자가 없는 항목을 만났을 때 가장
--    가까운 값을 억지로 고른다 — 그 데이터로 규칙을 고치면 틀린 근거로 고치게 된다.
--    자유 텍스트가 쌓인 뒤에 그것을 보고 목록을 만든다(이 리포의 방법론 그대로).
--
-- ⚠️ **거절 전용이 아니다.** 승인할 때도 "포스터에서 사례비 읽기 어려워 추정" 같은 메모가
--    남으면 유용하다 — 그래서 `review_status`와 짝을 맺는 CHECK를 걸지 않는다.
--
-- ⚠️ 크롤러는 이 칸을 **만들지 않는다**. 다만 중복 판정이 행 전체를 되쓰므로 읽어서 그대로
--    되쓴다(`CARRIED_ON_RESTRUCTURE`에도 들어가 재구조화가 지우지 않는다).
alter table review_data
  add column if not exists review_note text;
